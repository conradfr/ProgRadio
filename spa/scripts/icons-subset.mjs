// Bootstrap Icons subset: only the icons used by the project end up in the font and the css.
//
// Scans the twig templates, the spa and the php sources for "bi-*" classes and generates
// sass/icons/_bootstrap-icons-subset.scss + sass/icons/bootstrap-icons-subset.woff2 (git ignored).
//
//   node scripts/icons-subset.mjs          generate (files are written only if they changed)
//   node scripts/icons-subset.mjs --check  exit 1 if a used icon is missing from the subset
//
// Run by the vite plugin in vite.config.ts at dev server start and at build, also in the production
// docker build (tools/docker/www/Dockerfile copies templates/ and src/ next to spa/).
// During a dev session, a new icon needs "npm run icons" (or a dev server restart).

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);

const SPA_DIR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const ROOT_DIR = path.resolve(SPA_DIR, '..');

// directories scanned for icon classes, relative to the repository root
const SCAN_DIRS = ['templates', 'spa/src', 'src'];
const SCAN_EXTENSIONS = new Set(['.twig', '.html', '.vue', '.ts', '.js', '.php']);
const ICON_CLASS = /\bbi-([a-z0-9]+(?:-[a-z0-9]+)*)/g;

const OUTPUT_DIR = path.join(SPA_DIR, 'sass/icons');
const OUTPUT_SCSS = path.join(OUTPUT_DIR, '_bootstrap-icons-subset.scss');
const OUTPUT_FONT = path.join(OUTPUT_DIR, 'bootstrap-icons-subset.woff2');

const PACKAGE_DIR = path.dirname(require.resolve('bootstrap-icons/package.json'));
const PACKAGE_VERSION = JSON.parse(fs.readFileSync(path.join(PACKAGE_DIR, 'package.json'), 'utf8')).version;
const SOURCE_FONT = path.join(PACKAGE_DIR, 'font/fonts/bootstrap-icons.woff2');
const SOURCE_SCSS = path.join(PACKAGE_DIR, 'font/bootstrap-icons.scss');
const CODEPOINTS = JSON.parse(fs.readFileSync(path.join(PACKAGE_DIR, 'font/bootstrap-icons.json'), 'utf8'));

// ../templates has to be there, also in the docker build
export const sourcesAvailable = () => fs.existsSync(path.join(ROOT_DIR, 'templates'));

const listFiles = (dir) => fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
  const fullPath = path.join(dir, entry.name);

  if (entry.isDirectory()) {
    return entry.name === 'node_modules' ? [] : listFiles(fullPath);
  }

  return SCAN_EXTENSIONS.has(path.extname(entry.name)) ? [fullPath] : [];
});

// names of the icons used, only the ones existing in bootstrap icons (no false positives like "bi-directional")
export const findUsedIcons = () => {
  const icons = new Set();

  for (const dir of SCAN_DIRS) {
    const fullDir = path.join(ROOT_DIR, dir);
    if (!fs.existsSync(fullDir)) {
      continue;
    }

    for (const file of listFiles(fullDir)) {
      for (const match of fs.readFileSync(file, 'utf8').matchAll(ICON_CLASS)) {
        if (Object.prototype.hasOwnProperty.call(CODEPOINTS, match[1])) {
          icons.add(match[1]);
        }
      }
    }
  }

  return [...icons].sort();
};

// icons & bootstrap icons version of the committed subset, from the header of the generated scss
const readSubset = () => {
  if (!fs.existsSync(OUTPUT_SCSS) || !fs.existsSync(OUTPUT_FONT)) {
    return null;
  }

  const header = fs.readFileSync(OUTPUT_SCSS, 'utf8').match(/^\/\/ subset: (.*)\n\/\/ icons: (.*)$/m);

  return header ? { version: header[1], icons: header[2].split(' ').filter(Boolean) } : null;
};

// the shared ".bi::before" rule of the package, kept as is
const baseRule = () => {
  const scss = fs.readFileSync(SOURCE_SCSS, 'utf8');
  const start = scss.indexOf('.bi::before');
  const end = scss.indexOf('}', start);

  if (start === -1 || end === -1) {
    throw new Error(`[icons-subset] ".bi::before" rule not found in ${SOURCE_SCSS}`);
  }

  return scss.slice(start, end + 1);
};

const buildScss = (icons) => `// GENERATED by spa/scripts/icons-subset.mjs (npm run icons), do not edit.
// subset: bootstrap-icons ${PACKAGE_VERSION}
// icons: ${icons.join(' ')}

// used by the ".bi::before" rule copied from the package
$bootstrap-icons-font: "bootstrap-icons";

@font-face {
  font-display: block;
  font-family: $bootstrap-icons-font;
  // relative to sass/main_global.scss, which imports this file (sass doesn't rebase urls of imported files)
  src: url("./icons/bootstrap-icons-subset.woff2") format("woff2");
}

${baseRule()}

${icons.map(icon => `.bi-${icon}::before { content: "\\${CODEPOINTS[icon].toString(16)}"; }`).join('\n')}
`;

const writeIfChanged = (file, content) => {
  if (fs.existsSync(file) && Buffer.compare(fs.readFileSync(file), Buffer.from(content)) === 0) {
    return false;
  }

  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content);

  return true;
};

export const generate = async ({ log = console.log } = {}) => {
  const icons = findUsedIcons();

  if (icons.length === 0) {
    throw new Error('[icons-subset] no icon found, not overwriting the subset');
  }

  const subset = readSubset();
  const scssChanged = writeIfChanged(OUTPUT_SCSS, buildScss(icons));

  // the font only depends on the icons and the package version
  let fontChanged = false;
  if (!subset || subset.version !== `bootstrap-icons ${PACKAGE_VERSION}` || subset.icons.join(' ') !== icons.join(' ')) {
    const { default: subsetFont } = await import('subset-font');
    const text = icons.map(icon => String.fromCodePoint(CODEPOINTS[icon])).join('');
    const font = await subsetFont(fs.readFileSync(SOURCE_FONT), text, { targetFormat: 'woff2' });
    fontChanged = writeIfChanged(OUTPUT_FONT, font);
  }

  const changed = scssChanged || fontChanged;
  if (changed) {
    log(`[icons-subset] ${icons.length} icons, subset updated (${fs.statSync(OUTPUT_FONT).size} bytes font)`);
  }

  return { icons, changed };
};

// missing: used but not in the subset (blank icons). unused: in the subset but not used anymore (harmless)
export const check = () => {
  const icons = findUsedIcons();
  const subset = readSubset();

  if (!subset) {
    return { ok: false, reason: 'subset files not found', missing: icons, unused: [] };
  }

  const inSubset = new Set(subset.icons);
  const used = new Set(icons);
  const missing = icons.filter(icon => !inSubset.has(icon));
  const unused = subset.icons.filter(icon => !used.has(icon));
  const outdated = subset.version !== `bootstrap-icons ${PACKAGE_VERSION}`;

  return {
    ok: missing.length === 0 && !outdated,
    reason: outdated ? `generated for ${subset.version}, bootstrap-icons ${PACKAGE_VERSION} is installed` : null,
    missing,
    unused
  };
};

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  if (process.argv.includes('--check')) {
    const result = check();

    if (result.unused.length > 0) {
      console.warn(`[icons-subset] not used anymore (run "npm run icons"): ${result.unused.join(', ')}`);
    }

    if (!result.ok) {
      console.error(`[icons-subset] subset out of date${result.reason ? ` (${result.reason})` : ''}`
        + `${result.missing.length > 0 ? `, missing: ${result.missing.join(', ')}` : ''}. Run "npm run icons".`);
      process.exit(1);
    }

    console.log('[icons-subset] subset up to date');
  } else {
    const { icons, changed } = await generate();

    if (!changed) {
      console.log(`[icons-subset] ${icons.length} icons, subset up to date`);
    }
  }
}
